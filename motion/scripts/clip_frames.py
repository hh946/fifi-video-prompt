#!/usr/bin/env python3
"""Split a video clip into a numbered JPG sequence for XM.frames (used by the wall / thirds / strip / bigtype components).

Rendering screenshots each frame under file://, and seeking a <video> element is not frame-accurate, so footage is
pre-split into JPGs and components pick the frame for time t (deterministic).

Usage:
  python3 clip_frames.py <video> <out dir> [--start sec] [--dur sec] [--fps 30] [--width 1280] [--quality 3]

Output:
  <out dir>/f_00001.jpg ...  frame sequence
  <out dir>/clip.js          manifest: XM_CLIPS['<dir name>'] = { n, fps, w, h, dur, start, src, audio }
  <out dir>/clip.wav         the clip's original audio (48 kHz stereo). The frames are silent; if you want the original
                             sound, align clip.wav in your audio mix to the time the clip appears.
"""
import argparse, json, os, shutil, subprocess, sys


def probe(path):
    out = subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height:format=duration',
                          '-of', 'json', path], capture_output=True, text=True, check=True).stdout
    j = json.loads(out)
    s = j['streams'][0]
    return s['width'], s['height'], float(j['format']['duration'])


def has_audio(path):
    out = subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'a', '-show_entries', 'stream=index', '-of', 'csv=p=0', path],
                         capture_output=True, text=True).stdout
    return bool(out.strip())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('video'); ap.add_argument('out')
    ap.add_argument('--start', type=float, default=0); ap.add_argument('--dur', type=float, default=None)
    ap.add_argument('--fps', type=float, default=30); ap.add_argument('--width', type=int, default=1280)
    ap.add_argument('--quality', type=int, default=3, help='JPG quality, ffmpeg -q:v: 2 = best, 31 = worst')
    a = ap.parse_args()

    if not shutil.which('ffmpeg'): sys.exit('ffmpeg is required')
    W0, H0, D0 = probe(a.video)
    dur = min(a.dur if a.dur else D0 - a.start, D0 - a.start)
    if dur <= 0: sys.exit(f'Start {a.start}s is past the end of the video ({D0:.2f}s)')
    w = min(a.width, W0) // 2 * 2
    h = round(H0 * w / W0 / 2) * 2

    os.makedirs(a.out, exist_ok=True)
    for f in os.listdir(a.out):
        if f.startswith('f_') and f.endswith('.jpg'): os.remove(os.path.join(a.out, f))
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f'{a.start}', '-t', f'{dur}', '-i', a.video,
                    '-vf', f'fps={a.fps},scale={w}:{h}:flags=lanczos', '-q:v', str(a.quality), '-start_number', '1',
                    os.path.join(a.out, 'f_%05d.jpg')], check=True)
    n = len([f for f in os.listdir(a.out) if f.startswith('f_') and f.endswith('.jpg')])

    audio = None
    if has_audio(a.video):
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f'{a.start}', '-t', f'{dur}', '-i', a.video, '-vn',
                        '-ac', '2', '-ar', '48000', os.path.join(a.out, 'clip.wav')], check=True)
        audio = 'clip.wav'

    name = os.path.basename(os.path.normpath(a.out))
    meta = {'n': n, 'fps': a.fps, 'w': w, 'h': h, 'dur': round(n / a.fps, 4), 'start': a.start,
            'src': os.path.basename(a.video), 'audio': audio}
    with open(os.path.join(a.out, 'clip.js'), 'w', encoding='utf-8') as f:
        f.write('// generated by clip_frames.py, do not edit\n')
        f.write(f"(window.XM_CLIPS = window.XM_CLIPS || {{}})[{json.dumps(name, ensure_ascii=False)}] = {json.dumps(meta, ensure_ascii=False)};\n")
    size = sum(os.path.getsize(os.path.join(a.out, f)) for f in os.listdir(a.out)) / 1e6
    print(f'{name}: {n} frames {w}x{h} @{a.fps}fps, {meta["dur"]}s, {size:.1f} MB' + (', audio clip.wav' if audio else ', no audio track'))


if __name__ == '__main__':
    main()
